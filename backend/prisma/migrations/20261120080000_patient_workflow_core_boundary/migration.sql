-- No medical transition is removed without director review.
-- The marker detects accidental service bypass, not hostile schema-owner SQL.
CREATE OR REPLACE FUNCTION patient_workflow_transition_guard() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE allowed text[];
BEGIN
  IF current_user <> 'aulia_app' OR NEW."workflowStatus" IS NOT DISTINCT FROM OLD."workflowStatus" THEN RETURN NEW; END IF;
  PERFORM pg_advisory_xact_lock(hashtext('patient-workflow:' || NEW."clinicId" || ':' || NEW."id"));
  IF current_setting('app.workflow_patient', true) IS DISTINCT FROM NEW."id" THEN
    RAISE EXCEPTION 'PatientWorkflowService requis' USING ERRCODE = 'check_violation';
  END IF;
  allowed := CASE OLD."workflowStatus"::text
    WHEN 'EN_ATTENTE_DE_PAIEMENT' THEN ARRAY['EN_ATTENTE_VALIDATION_CAISSE','EN_ATTENTE_INFIRMERIE','EN_ATTENTE_MEDECIN','EN_CONSULTATION','EN_LABORATOIRE','EN_RADIOLOGIE','EN_PHARMACIE','HOSPITALISE','TERMINE','ANNULE']
    WHEN 'EN_ATTENTE_VALIDATION_CAISSE' THEN ARRAY['EN_ATTENTE_DE_PAIEMENT','EN_ATTENTE_INFIRMERIE','EN_ATTENTE_MEDECIN','EN_CONSULTATION','EN_LABORATOIRE','EN_RADIOLOGIE','EN_PHARMACIE','HOSPITALISE','TERMINE','ANNULE']
    WHEN 'EN_ATTENTE_INFIRMERIE' THEN ARRAY['EN_ATTENTE_DE_PAIEMENT','EN_ATTENTE_VALIDATION_CAISSE','EN_ATTENTE_MEDECIN','EN_CONSULTATION','EN_LABORATOIRE','EN_RADIOLOGIE','EN_PHARMACIE','HOSPITALISE','TERMINE','ANNULE']
    WHEN 'EN_ATTENTE_MEDECIN' THEN ARRAY['EN_ATTENTE_DE_PAIEMENT','EN_ATTENTE_VALIDATION_CAISSE','EN_ATTENTE_INFIRMERIE','EN_CONSULTATION','EN_LABORATOIRE','EN_RADIOLOGIE','EN_PHARMACIE','HOSPITALISE','TERMINE','ANNULE']
    WHEN 'EN_LABORATOIRE' THEN ARRAY['EN_ATTENTE_DE_PAIEMENT','EN_ATTENTE_VALIDATION_CAISSE','EN_ATTENTE_INFIRMERIE','EN_ATTENTE_MEDECIN','EN_CONSULTATION','EN_RADIOLOGIE','EN_PHARMACIE','HOSPITALISE','TERMINE','ANNULE']
    WHEN 'EN_RADIOLOGIE' THEN ARRAY['EN_ATTENTE_DE_PAIEMENT','EN_ATTENTE_VALIDATION_CAISSE','EN_ATTENTE_INFIRMERIE','EN_ATTENTE_MEDECIN','EN_CONSULTATION','EN_LABORATOIRE','EN_PHARMACIE','HOSPITALISE','TERMINE','ANNULE']
    WHEN 'EN_PHARMACIE' THEN ARRAY['EN_ATTENTE_DE_PAIEMENT','EN_ATTENTE_VALIDATION_CAISSE','EN_ATTENTE_INFIRMERIE','EN_ATTENTE_MEDECIN','EN_CONSULTATION','EN_LABORATOIRE','EN_RADIOLOGIE','HOSPITALISE','TERMINE','ANNULE']
    WHEN 'EN_CONSULTATION' THEN ARRAY['EN_ATTENTE_DE_PAIEMENT','EN_ATTENTE_VALIDATION_CAISSE','EN_LABORATOIRE','EN_RADIOLOGIE','EN_PHARMACIE','HOSPITALISE','TERMINE','ANNULE']
    WHEN 'HOSPITALISE' THEN ARRAY['EN_CONSULTATION','EN_LABORATOIRE','EN_RADIOLOGIE','EN_PHARMACIE','TERMINE','ANNULE']
    WHEN 'TERMINE' THEN ARRAY['EN_ATTENTE_DE_PAIEMENT','EN_ATTENTE_VALIDATION_CAISSE','EN_ATTENTE_INFIRMERIE','EN_ATTENTE_MEDECIN','EN_CONSULTATION','HOSPITALISE']
    WHEN 'ANNULE' THEN ARRAY['EN_ATTENTE_DE_PAIEMENT','EN_ATTENTE_VALIDATION_CAISSE','EN_ATTENTE_INFIRMERIE','EN_ATTENTE_MEDECIN','EN_CONSULTATION','HOSPITALISE']
    ELSE ARRAY[]::text[]
  END;
  IF NOT (NEW."workflowStatus"::text = ANY (allowed)) THEN
    RAISE EXCEPTION 'Transition de parcours patient interdite : % -> %', OLD."workflowStatus", NEW."workflowStatus" USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END;
$$;
